"""Small, credential-free messages between the GUI and its worker."""
import json
import os
from pathlib import Path
import re
from datetime import datetime, timezone


def validate_profile(name):
    reserved = {"CON", "PRN", "AUX", "NUL"} | {f"COM{i}" for i in range(1, 10)} | {f"LPT{i}" for i in range(1, 10)}
    if not re.fullmatch(r"[\w-]{1,40}", name) or name.upper() in reserved:
        raise ValueError("账号档案名只可包含文字、数字、下划线和短横线")
    return name


def profile_path(root, name):
    return Path(root) / "profiles" / validate_profile(name)


class EventSink:
    def __init__(self, directory, filename):
        if not re.fullmatch(r"gui-[0-9a-f]{32}\.jsonl", filename):
            raise ValueError("Invalid event filename")
        self.directory = Path(directory)
        self.directory.mkdir(parents=True, exist_ok=True, mode=0o700)
        self.path = self.directory / filename
        self.stream = self.path.open("x", encoding="utf-8")
        os.chmod(self.path, 0o600)
        # Only rotate files generated by this GUI, never user files or core code.
        old = sorted(self.directory.glob("gui-*.jsonl"), key=lambda p: p.stat().st_mtime, reverse=True)
        for path in old[3:]:
            if path != self.path:
                try:
                    path.unlink(missing_ok=True)
                except OSError:
                    pass  # Another Windows process may still hold this file open.

    def emit(self, kind, **values):
        record = {"event": kind, "at": datetime.now(timezone.utc).isoformat(), **values}
        line = json.dumps(record, ensure_ascii=False) + "\n"
        if self.stream.tell() > 1024 * 1024 and kind not in ("error", "done"):
            return
        self.stream.write(line)
        self.stream.flush()

    def close(self):
        self.stream.close()


class EventReader:
    def __init__(self, path):
        self.path = Path(path)
        self.offset = 0

    def read(self):
        if not self.path.exists():
            return []
        result = []
        with self.path.open("rb") as stream:
            stream.seek(self.offset)
            for _ in range(100):
                start = stream.tell()
                line = stream.readline(65537)
                if not line:
                    break
                if not line.endswith(b"\n"):
                    if len(line) == 65537:
                        # Reject oversized IPC records without getting stuck on them.
                        while line and not line.endswith(b"\n"):
                            line = stream.readline(65537)
                        self.offset = stream.tell()
                        continue
                    stream.seek(start)
                    break
                self.offset = stream.tell()
                try:
                    value = json.loads(line)
                    if isinstance(value, dict) and "event" in value:
                        result.append(value)
                except (ValueError, UnicodeError):
                    continue
        return result
